export type PlatformKey = Key;
export type PlatformText = (key: Key, vars?: Record<string, string | number>) => string;

const fill = (text: string, vars?: Record<string, string | number>) => (vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text);

/** Texto en el idioma pedido, con variables {nombre}. */
export const textFor = (language: string, key: Key, vars?: Record<string, string | number>) => fill(language === 'en' ? en[key] : es[key], vars);

/** ¿Existe un texto para esta clave? (para traducir valores que llegan del servidor sin mostrar códigos crudos). */
export const hasText = (key: string): key is Key => key in es;

/** Mensaje para un código de error de la API (si existe en la tabla), si no el genérico. */
export function errorText(pt: PlatformText, code: string | undefined): string {
  if (code === 'offline_error' || code === 'timeout_error') return pt('network');
  return code && hasText(code) ? pt(code) : pt('unknown_error');
}

/** Sin respuesta del servidor (se cortó la conexión o venció el tiempo): no se sabe si la acción se aplicó. */
export const isUncertain = (code: string | undefined) => code === 'offline_error' || code === 'timeout_error';

/** Acción de la bitácora en palabras (nunca el código interno). */
export function auditActionText(pt: PlatformText, action: string): string {
  if (action.startsWith('cli.')) return pt('act_cli');
  if (action.startsWith('denied:')) return pt('act_denied');
  const key = `act_${action.replace(/\./g, '_')}`;
  return hasText(key) ? pt(key) : pt('act_other');
}
