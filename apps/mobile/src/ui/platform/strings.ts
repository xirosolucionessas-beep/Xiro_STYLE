export type PlatformText = (key: Key) => string;

export function usePlatformText(): { pt: PlatformText; language: string } {
  const { language } = useSettings();
  return { pt: (key) => (language === 'en' ? en[key] : es[key]), language };
}

/** Mensaje para un código de error de la API (si existe en la tabla), si no el genérico. */
export function errorText(pt: PlatformText, code: string | undefined): string {
  if (code === 'offline_error' || code === 'timeout_error') return pt('network');
  return code && code in es ? pt(code as Key) : pt('unknown_error');
}
